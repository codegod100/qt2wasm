"""JavaScript bindings for a component: `jco transpile` + a small loader.

qt2wasm build writes <name>-js/ next to <name>.wasm (--js, on by default):

  <name>.js, <name>.d.ts,        jco transpile --instantiation async: ES module
  <name>.core*.wasm,             exporting instantiate(getCoreModule, imports)
  interfaces/*.d.ts              and the TypeScript types of every interface
  index.js, index.d.ts           load(hostImports): instantiates the component
                                 with the WASI preview2 shim and the core
                                 modules next to it; hostImports are the
                                 component's own imports (e.g. the Qt signals
                                 interface <name>-events), keyed without the
                                 @version, as the jco output expects
  package.json                   "type": "module", main index.js, and the
                                 @bytecodealliance/preview2-shim dependency
  node_modules/@bytecodealliance/preview2-shim
                                 that shim, copied from the jco install (pure
                                 JS, ~1 MB), so `node` runs it with no npm step

    import { load } from './counter-js/index.js';
    const { counter } = await load({
      'demo:counter/counter-events': { valueChanged(src, v) {}, overflowed(src, why, at) {} },
    });
    const c = new counter.Counter();

jco comes from the `jco` conda package on prefix.dev/nandi-testing (recipes/jco),
a run dependency of qt2wasm; QT2WASM_JCO overrides it.
"""

from __future__ import annotations

import json
import os
import re
import shutil
import subprocess
from pathlib import Path

SHIM = "@bytecodealliance/preview2-shim"


class JsError(RuntimeError):
    pass


def find_jco() -> Path | None:
    if os.environ.get("QT2WASM_JCO"):
        return Path(os.environ["QT2WASM_JCO"])
    found = shutil.which("jco")
    if found:
        return Path(found)
    prefix = Path(os.environ.get("CONDA_PREFIX") or "/nonexistent")
    return prefix / "bin" / "jco" if (prefix / "bin" / "jco").exists() else None


def find_shim(jco: Path) -> Path | None:
    """preview2-shim inside the jco install: <prefix>/lib/node_modules/
    @bytecodealliance/jco/node_modules/@bytecodealliance/preview2-shim."""
    real = jco.resolve()  # bin/jco -> .../@bytecodealliance/jco/dist/jco.js
    for d in real.parents:
        for cand in (d / "node_modules" / SHIM, d / "lib" / "node_modules" / SHIM):
            if (cand / "package.json").is_file():
                return cand
        if d.name == "node_modules":
            break
    return None


def _version(jco: Path) -> str:
    try:
        return subprocess.run(
            [str(jco), "--version"], capture_output=True, text=True, check=True
        ).stdout.strip()
    except (OSError, subprocess.CalledProcessError):
        return "?"


def _host_imports(js: str, dts: str) -> list[tuple[str, str | None]]:
    """The component's non-WASI imports, as (unversioned key, type alias).
    The keys come from the JS (`imports["pkg:ns/iface"]`), which is what
    instantiate() reads; the types from <name>.d.ts's ImportObject."""
    keys = sorted(set(re.findall(r'imports\["([^"]+)"\]', js)))
    types = {}
    for full, alias in re.findall(r'^\s*"([^"]+)": typeof (\w+),?$', dts, re.MULTILINE):
        types[full.split("@", 1)[0]] = alias
    return [(k, types.get(k)) for k in keys if not k.startswith("wasi:")]


def write_loader(dst: Path, name: str, shim_version: str) -> None:
    js = (dst / f"{name}.js").read_text()
    dts = (dst / f"{name}.d.ts").read_text()
    host = _host_imports(js, dts)
    (dst / "index.js").write_text(
        f"""// Generated by qt2wasm (jsgen.py). Do not edit; regenerate.
// load(hostImports) instantiates {name}.wasm (transpiled by jco) with the WASI
// preview2 shim. hostImports: the component's own imports, unversioned keys.
import {{ readFile }} from 'node:fs/promises';
import {{ WASIShim }} from '{SHIM}/instantiation';
import {{ instantiate }} from './{name}.js';

const here = new URL('./', import.meta.url);

export async function load(hostImports = {{}}, {{ wasi }} = {{}}) {{
  const imports = {{ ...(wasi ?? new WASIShim().getImportObject()), ...hostImports }};
  return instantiate((f) => readFile(new URL(f, here)).then((b) => WebAssembly.compile(b)), imports);
}}

export {{ instantiate }};
"""
    )
    aliases = sorted({a for _, a in host if a})
    imp = "".join(
        f"import type * as {a} from './interfaces/{_iface_file(dts, a)}';\n"
        for a in aliases
    )
    fields = "".join(
        f"  {json.dumps(k)}: {('typeof ' + a) if a else 'Record<string, Function>'},\n"
        for k, a in host
    )
    (dst / "index.d.ts").write_text(
        f"""// Generated by qt2wasm (jsgen.py). Do not edit; regenerate.
import {{ instantiate }} from './{name}.js';
{imp}
/** The component's own (non-WASI) imports, keyed without the @version. */
export interface HostImports {{
{fields}}}

export type Root = Awaited<ReturnType<typeof instantiate>>;

/** Instantiate the component with the WASI preview2 shim (or `wasi`). */
export function load(hostImports: HostImports, options?: {{ wasi?: object }}): Promise<Root>;

export {{ instantiate }};
"""
    )
    (dst / "package.json").write_text(
        json.dumps(
            {
                "name": name,
                "private": True,
                "type": "module",
                "main": "index.js",
                "types": "index.d.ts",
                "exports": {".": {"types": "./index.d.ts", "default": "./index.js"}},
                "dependencies": {SHIM: f"^{shim_version}"},
            },
            indent=2,
        )
        + "\n"
    )


def _iface_file(dts: str, alias: str) -> str:
    m = re.search(
        rf"import type \* as {alias} from '\./interfaces/([^']+)';", dts
    )
    return m.group(1) if m else f"{alias}.js"


def transpile(component: Path, dst: Path, name: str, jco: Path) -> Path:
    """jco transpile COMPONENT into DST (replaced), plus index.js/.d.ts,
    package.json and the vendored preview2 shim. Returns DST."""
    shim = find_shim(jco)
    if shim is None:
        raise JsError(f"{SHIM} not found next to {jco} (the jco package ships it)")
    if dst.exists():
        shutil.rmtree(dst)
    cmd = [
        str(jco),
        "transpile",
        str(component),
        "-o",
        str(dst),
        "--name",
        name,
        "--instantiation",
        "async",
        "--quiet",
    ]
    p = subprocess.run(cmd, capture_output=True, text=True)
    if p.returncode != 0:
        raise JsError(f"jco transpile failed:\n{p.stdout}{p.stderr}".strip())
    shim_version = json.loads((shim / "package.json").read_text())["version"]
    write_loader(dst, name, shim_version)
    vend = dst / "node_modules" / SHIM
    vend.parent.mkdir(parents=True, exist_ok=True)
    shutil.copytree(shim, vend, symlinks=False)
    return dst
