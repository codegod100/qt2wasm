"""Model -> WIT text.

Layout of the generated package:

* ``types``: Qt value records (point, rect, rgba, image, ...), Q_GADGET
  records, and every Q_ENUM / Q_FLAG the exported classes use.
* one interface per exported class, holding its resource.
* ``<interface>-events``: one function per signal, imported, so the host
  hears signals as calls. Each takes ``source: u32``, the instance id that
  the resource's ``id`` method returns.
* world ``component``: exports the class interfaces, imports the events.
"""

from __future__ import annotations

from qt2wasm.model import QT_RECORDS, Model, WitType


def _type_names(t: WitType, acc: set[str]) -> None:
    if t.kind in ("qtrecord", "enum", "flags", "gadget"):
        acc.add(t.wit)
    for i in t.inner:
        _type_names(i, acc)


def _fn(params, result) -> str:
    ps = ", ".join(f"{p.name}: {p.type.wit}" for p in params)
    return f"func({ps})" + (f" -> {result.wit}" if result else "")


def generate(model: Model) -> str:
    out: list[str] = []
    w = out.append
    w("// Generated by qt2wasm from moc metatypes. Do not edit; regenerate.")
    w(f"package {model.package};")
    w("")

    has_types = bool(model.uses_qt_types or model.gadgets or model.enums)
    if has_types:
        w("/// Qt value types, records from Q_GADGETs, and Q_ENUM/Q_FLAG enums.")
        w("interface types {")
        for cpp in sorted(model.uses_qt_types, key=lambda c: QT_RECORDS[c][0]):
            name, fields = QT_RECORDS[cpp]
            note = (
                " Pixels are RGBA8888, rows tightly packed." if cpp == "QImage" else ""
            )
            w(f"    /// {cpp}.{note}")
            w(f"    record {name} {{")
            for fname, ftype in fields:
                w(f"        {fname}: {ftype},")
            w("    }")
        for g in model.gadgets.values():
            w(f"    /// Q_GADGET {g.cpp}.")
            w(f"    record {g.wit_name} {{")
            for f in g.fields:
                w(f"        {f.wit_name}: {f.type.wit},")
            w("    }")
        for e in model.enums:
            from qt2wasm.names import wit_ident

            kind = "flags" if e.is_flag else "enum"
            if e.is_flag and len(e.values) > 32:
                raise ValueError(f"{e.cpp}: WIT flags hold at most 32 values")
            w(f"    /// {'Q_FLAG' if e.is_flag else 'Q_ENUM'} {e.cpp}.")
            w(f"    {kind} {e.wit_name} {{")
            for v in e.values:
                w(f"        {wit_ident(v)},")
            w("    }")
        w("}")
        w("")

    for c in model.classes:
        used: set[str] = set()
        for m in c.methods:
            for p in m.params:
                _type_names(p.type, used)
            if m.result:
                _type_names(m.result, used)
        for p in c.ctor_params:
            _type_names(p.type, used)
        w(f"/// Exported from {c.cpp} ({c.header}).")
        w(f"interface {c.interface} {{")
        if used:
            w(f"    use types.{{{', '.join(sorted(used))}}};")
            w("")
        w(f"    resource {c.resource} {{")
        ps = ", ".join(f"{p.name}: {p.type.wit}" for p in c.ctor_params)
        w(f"        constructor({ps});")
        w("        /// Instance id; signals from this instance carry it as `source`.")
        w("        id: func() -> u32;")
        for m in c.methods:
            tag = {"getter": "Q_PROPERTY read", "setter": "Q_PROPERTY write"}.get(
                m.kind
            )
            if tag:
                w(f"        /// {tag}: {c.cpp}::{m.cpp_name}")
            w(f"        {m.wit_name}: {_fn(m.params, m.result)};")
        w("    }")
        w("}")
        w("")
        if c.signals:
            used = set()
            for s in c.signals:
                for p in s.params:
                    _type_names(p.type, used)
            w(f"/// Signals of {c.cpp}, delivered to the host as calls.")
            w(f"interface {c.events_interface} {{")
            if used:
                w(f"    use types.{{{', '.join(sorted(used))}}};")
                w("")
            for s in c.signals:
                ps = ", ".join(
                    ["source: u32"] + [f"{p.name}: {p.type.wit}" for p in s.params]
                )
                w(f"    {s.wit_name}: func({ps});")
            w("}")
            w("")

    w("world component {")
    for c in model.classes:
        if c.signals:
            w(f"    import {c.events_interface};")
    for c in model.classes:
        w(f"    export {c.interface};")
    w("}")
    return "\n".join(out) + "\n"
